// Test-target-only focus admission, selected by baseline_input_focus.h.
// Synthetic window/key events do not test native focus or SDL keyboard state.
SDL_Window* fixture_focus = nullptr;
SDL_Window* baseline_fixture_keyboard_focus() noexcept { return fixture_focus; }

namespace {
namespace host = baseline::host;
using tooie::input::Action;
using tooie::input::Device;

void require(bool condition, const char* message) {
    if (!condition) throw std::runtime_error(message);
}

// Only fixture-owned temporary files and SDL objects are destroyed here.
struct Fixture {
    std::filesystem::path profile;
    SDL_Window* window = nullptr;
    std::array<SDL_Joystick*, 2> pads{};
    std::array<SDL_GameController*, 2> controllers{};
    bool sdl = false, redirected = false;

    ~Fixture() {
        host::shutdown();
        fixture_focus = nullptr;
        for (auto* controller : controllers) if (controller) SDL_GameControllerClose(controller);
        for (auto* pad : pads) if (pad) {
            const auto instance = SDL_JoystickInstanceID(pad);
            SDL_JoystickClose(pad);
            for (int index = 0; index < SDL_NumJoysticks(); ++index)
                if (SDL_JoystickGetDeviceInstanceID(index) == instance) {
                    SDL_JoystickDetachVirtual(index);
                    break;
                }
        }
        if (window) SDL_DestroyWindow(window);
        if (sdl) SDL_Quit();
        if (redirected) std::fclose(stderr);
        if (!profile.empty()) {
            std::error_code ignored;
            std::filesystem::remove_all(profile, ignored);
        }
    }

    // Every controller event is generated by SDL, then delivered to the real host.
    bool drain(Uint32 type = 0, SDL_JoystickID instance = -1, int control = -1) {
        bool observed = false;
        SDL_Event event{};
        while (SDL_PollEvent(&event)) {
            if (event.type == type) {
                if (type == SDL_CONTROLLERAXISMOTION)
                    observed |= event.caxis.which == instance && event.caxis.axis == control;
                else
                    observed |= event.cbutton.which == instance && event.cbutton.button == control;
            }
            host::handle_event(event);
        }
        return observed;
    }

    void setup() {
        const auto unique = std::chrono::steady_clock::now().time_since_epoch().count();
        const auto candidate = std::filesystem::temp_directory_path() /
            ("tooie-baseline-input-host-" + std::to_string(unique));
        require(std::filesystem::create_directory(candidate), "fixture temp profile creation failed");
        profile = candidate;
        redirected = std::freopen((profile / "host-stderr.log").string().c_str(), "w", stderr) != nullptr;
        require(redirected, "fixture stderr redirection failed");
        SDL_SetMainReady();
        require(SDL_setenv("SDL_VIDEODRIVER", "dummy", 1) == 0, "fixture dummy driver selection failed");
        // The dummy driver's internal focus stays NULL. Keep SDL virtual-pad
        // transport enabled; the real mapper's baseline focus policy still runs.
        require(SDL_SetHintWithPriority(SDL_HINT_JOYSTICK_ALLOW_BACKGROUND_EVENTS,
            "1", SDL_HINT_OVERRIDE) == SDL_TRUE, "fixture virtual event transport hint rejected");
        require(SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS | SDL_INIT_JOYSTICK |
            SDL_INIT_GAMECONTROLLER) == 0, "fixture SDL dummy initialization failed");
        sdl = true;
        for (unsigned i = 0; i < pads.size(); ++i) {
            SDL_VirtualJoystickDesc desc{};
            desc.version = SDL_VIRTUAL_JOYSTICK_DESC_VERSION;
            desc.type = SDL_JOYSTICK_TYPE_GAMECONTROLLER;
            desc.naxes = SDL_CONTROLLER_AXIS_MAX;
            desc.nbuttons = SDL_CONTROLLER_BUTTON_MAX;
            desc.vendor_id = 0x1209;
            desc.product_id = Uint16(0x4200 + i); // Distinct persistent identities.
            desc.name = i == 0 ? "Baseline input selected fixture" : "Baseline input foreign fixture";
            const int device = SDL_JoystickAttachVirtualEx(&desc);
            require(device >= 0 && SDL_IsGameController(device), "fixture virtual controller attachment failed");
            pads[i] = SDL_JoystickOpen(device);
            controllers[i] = SDL_GameControllerOpen(device);
            require(pads[i] && controllers[i], "fixture virtual controller open failed");
            // SDL 2.26.3 virtual triggers use the full Sint16 range; the mapped
            // GameController trigger uses 0..32767, not -32768..32767.
            require(SDL_JoystickSetVirtualAxis(pads[i], SDL_CONTROLLER_AXIS_TRIGGERLEFT,
                SDL_JOYSTICK_AXIS_MIN) == 0 &&
                SDL_JoystickSetVirtualAxis(pads[i], SDL_CONTROLLER_AXIS_TRIGGERRIGHT,
                SDL_JOYSTICK_AXIS_MIN) == 0, "fixture trigger rest assignment failed");
        }
        SDL_GameControllerUpdate();
        for (auto* controller : controllers)
            for (auto axis : {SDL_CONTROLLER_AXIS_TRIGGERLEFT, SDL_CONTROLLER_AXIS_TRIGGERRIGHT}) {
                const int value = SDL_GameControllerGetAxis(controller, axis);
                require(value >= 0 && value <= 16000, "fixture trigger rest not neutral");
            }
        window = SDL_CreateWindow("baseline input host test", 0, 0, 64, 64, SDL_WINDOW_SHOWN);
        require(window != nullptr, "fixture dummy window creation failed");
        host::initialize(window, profile);
        host::publish_ready(true); // No renderer needed for host admission.
        drain();
        focus(); // Synthetic admission; resolve the real mapper's focus transition.
        // Select through the same host request queue used by the menu, avoiding
        // dependence on enumeration order or any physically connected controller.
        host::Request select{};
        select.kind = host::RequestKind::Controller;
        select.value = SDL_JoystickInstanceID(pads[0]);
        require(host::enqueue(select), "fixture controller selection queue failed");
        host::tick(false);
        require(tooie::input::selected_controller_instance() == select.value,
            "host did not select fixture controller");
        tooie::input::host().set_menu_open(true);
        require(host::tick(false).focused && host::menu_open(), "host menu/focus admission failed");
    }

    void focus(bool gained = true) {
        fixture_focus = gained ? window : nullptr;
        SDL_Event event{};
        event.type = SDL_WINDOWEVENT;
        event.window.windowID = SDL_GetWindowID(window);
        event.window.event = gained ? SDL_WINDOWEVENT_FOCUS_GAINED : SDL_WINDOWEVENT_FOCUS_LOST;
        host::handle_event(event);
        host::tick(false); // Clears the mapper's pending focus transition.
    }

    void button(unsigned pad, SDL_GameControllerButton button, bool pressed) {
        require(SDL_JoystickSetVirtualButton(pads[pad], button, pressed ? 1 : 0) == 0,
            "fixture virtual button assignment failed");
        SDL_GameControllerUpdate();
        require(bool(SDL_GameControllerGetButton(controllers[pad], button)) == pressed,
            "fixture mapped button state incorrect");
        require(drain(pressed ? SDL_CONTROLLERBUTTONDOWN : SDL_CONTROLLERBUTTONUP,
            SDL_JoystickInstanceID(pads[pad]), button), "fixture SDL controller button event missing");
    }

    void trigger(bool pressed) {
        require(SDL_JoystickSetVirtualAxis(pads[0], SDL_CONTROLLER_AXIS_TRIGGERRIGHT,
            pressed ? SDL_JOYSTICK_AXIS_MAX : SDL_JOYSTICK_AXIS_MIN) == 0,
            "fixture virtual trigger assignment failed");
        SDL_GameControllerUpdate();
        const int value = SDL_GameControllerGetAxis(controllers[0], SDL_CONTROLLER_AXIS_TRIGGERRIGHT);
        require(pressed ? value > 22000 : value >= 0 && value <= 16000,
            "fixture mapped trigger state incorrect");
        require(drain(SDL_CONTROLLERAXISMOTION, SDL_JoystickInstanceID(pads[0]),
            SDL_CONTROLLER_AXIS_TRIGGERRIGHT), "fixture SDL controller axis event missing");
    }

    void f4(Uint16 modifiers = KMOD_NONE, Uint8 repeat = 0, Uint32 type = SDL_KEYDOWN) {
        SDL_Event event{};
        event.type = type;
        event.key.windowID = SDL_GetWindowID(window);
        event.key.state = type == SDL_KEYDOWN ? SDL_PRESSED : SDL_RELEASED;
        event.key.repeat = repeat;
        event.key.keysym.scancode = SDL_SCANCODE_F4;
        event.key.keysym.sym = SDLK_F4;
        event.key.keysym.mod = modifiers;
        host::handle_event(event);
    }

    std::string log() {
        std::fflush(stderr);
        std::ifstream file(profile / "host-stderr.log");
        require(bool(file), "fixture stderr log read failed");
        return {std::istreambuf_iterator<char>(file), std::istreambuf_iterator<char>()};
    }

    std::shared_ptr<const host::Snapshot> snapshot() {
        auto state = host::take_render_input().snapshot;
        require(bool(state), "host snapshot missing");
        return state;
    }

    void capture(Action action) {
        host::Request request{};
        request.kind = host::RequestKind::Capture;
        request.action = action;
        request.device = Device::Button;
        request.slot = 0;
        require(host::enqueue(request), "host capture queue rejected request");
        require(!host::tick(false).physical.nonneutral(), "menu capture leaked gameplay input");
    }

    void cooldown() {
        require(!host::tick(false).physical.nonneutral(), "menu release leaked gameplay input");
        require(tooie::input::input_suppressed(), "capture release cooldown ended immediately");
        SDL_Delay(270);
        host::tick(false);
        require(!tooie::input::input_suppressed(), "neutral capture cooldown did not release input");
    }
};

void check_bindings() {
    require(tooie::input::get_binding(Action::Z, Device::Button, 0).code == SDL_CONTROLLER_BUTTON_X &&
        tooie::input::get_binding(Action::Z, Device::AxisPositive, 0).code == -1,
        "Z button binding did not replace left-trigger slot");
    require(tooie::input::get_binding(Action::Start, Device::AxisPositive, 0).code == SDL_CONTROLLER_AXIS_TRIGGERRIGHT &&
        tooie::input::get_binding(Action::Start, Device::Button, 0).code == -1,
        "Start trigger binding did not replace START button slot");
}
}

int main() {
    try {
        Fixture fixture;
        fixture.setup();
        require(tooie::input::get_binding(Action::Z, Device::AxisPositive, 0).code == SDL_CONTROLLER_AXIS_TRIGGERLEFT &&
            tooie::input::get_binding(Action::Start, Device::Button, 0).code == SDL_CONTROLLER_BUTTON_START,
            "fresh disposable profile lacks baseline Z/Start defaults");

        // A: Held input must prevent arming; rest must admit capture. A foreign
        // pad cannot steal the armed request from the selected pad.
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, true);
        fixture.capture(Action::Z);
        require(fixture.snapshot()->capture.active && fixture.snapshot()->capture.arming,
            "capture armed while selected control was held");
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, false);
        host::tick(false);
        require(fixture.snapshot()->capture.active && !fixture.snapshot()->capture.arming,
            "neutral selected controller did not arm Z capture");
        // SDL transport remains enabled, but real mapper focus policy must
        // reject selected-pad capture while our admitted focus is absent.
        fixture.focus(false);
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, true);
        require(!host::tick(false).focused && fixture.snapshot()->capture.active,
            "unfocused selected press completed capture");
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, false);
        fixture.focus(true);
        host::tick(false);
        fixture.button(1, SDL_CONTROLLER_BUTTON_X, true);
        require(!host::tick(false).physical.nonneutral() && fixture.snapshot()->capture.active,
            "foreign controller stole Z capture or leaked input");
        fixture.button(1, SDL_CONTROLLER_BUTTON_X, false);
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, true);
        host::tick(false);
        require(!fixture.snapshot()->capture.active, "selected controller did not finish Z capture");
        require(tooie::input::get_binding(Action::Z, Device::Button, 0).code == SDL_CONTROLLER_BUTTON_X &&
            tooie::input::get_binding(Action::Z, Device::AxisPositive, 0).code == -1,
            "Z selected button did not replace default trigger");
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, false);
        fixture.cooldown();

        // B: A controller-row request discovers an axis as well as a button.
        fixture.capture(Action::Start);
        require(fixture.snapshot()->capture.active && !fixture.snapshot()->capture.arming,
            "neutral controller did not arm Start capture");
        fixture.trigger(true);
        host::tick(false);
        require(!fixture.snapshot()->capture.active, "selected trigger did not finish Start capture");
        check_bindings();
        fixture.trigger(false);
        fixture.cooldown();

        // C: Publish real gameplay bits after the host relinquishes the menu.
        host::request_close();
        host::note_game_started();
        require(!host::tick(true).physical.nonneutral() && !host::menu_open(),
            "neutral gameplay handoff failed");
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, true);
        require((host::tick(true).physical.buttons & 0x2000) != 0, "new X binding did not publish Z gameplay bit");
        fixture.button(0, SDL_CONTROLLER_BUTTON_X, false);
        require(!host::tick(true).physical.nonneutral(), "Z release remained held");
        fixture.trigger(true);
        require((host::tick(true).physical.buttons & 0x1000) != 0, "new trigger binding did not publish Start gameplay bit");
        fixture.trigger(false);
        require(!host::tick(true).physical.nonneutral(), "Start trigger release remained held");
        fixture.button(0, SDL_CONTROLLER_BUTTON_START, true);
        require((host::tick(true).physical.buttons & 0x1000) == 0, "old START button still published Start gameplay bit");
        fixture.button(0, SDL_CONTROLLER_BUTTON_START, false);
        host::tick(true);

        // D: Re-read real on-disk settings; no fake settings store or host adapter.
        if (!tooie::frontend::settings::flush()) {
            std::string diagnostic = "binding settings flush failed; profile=" + fixture.profile.string() +
                "; recovery=" + std::string(tooie::frontend::settings::recovery_notice());
            for (const char* name : {"tooie_imgui.json", "tooie_imgui.json.tmp", "tooie_imgui.json.bak"}) {
                std::error_code error;
                const auto file = fixture.profile / name;
                const bool present = std::filesystem::exists(file, error);
                diagnostic += "; " + std::string(name) + " exists=" + std::to_string(present) +
                    " status_error=" + error.message();
                if (present && !error) {
                    std::ifstream input(file);
                    diagnostic += " readable=" + std::to_string(bool(input));
                }
            }
            throw std::runtime_error(diagnostic);
        }
        require(std::filesystem::is_regular_file(fixture.profile / "tooie_imgui.json"),
            "binding settings file missing");
        host::shutdown();
        host::initialize(fixture.window, fixture.profile);
        fixture.focus();
        require(tooie::input::selected_controller_instance() == SDL_JoystickInstanceID(fixture.pads[0]),
            "selected controller identity did not survive host restart");
        check_bindings();

        // E: F4 uses the real host path, including binding/capture precedence.
        host::publish_ready(true);
        fixture.drain();
        host::tick(false);
        require(!host::menu_open() && !tooie::input::input_suppressed(), "F4 initial host admission failed");
        fixture.f4();
        host::tick(false);
        const auto first_log = fixture.log();
        require(first_log.find("issue-marker seq=1 local=") != std::string::npos &&
            first_log.find(" utc=") != std::string::npos && first_log.find(" version=") != std::string::npos &&
            first_log.find(" game_started=0 menu=0 ") != std::string::npos &&
            first_log.find(" output_rate=") != std::string::npos && first_log.find(" fullscreen=") != std::string::npos &&
            first_log.find(" controller=\"") != std::string::npos,
            "F4 marker line lacks sequence, timestamps, version or current state");
        require(fixture.snapshot()->toast.find("#1") != std::string::npos,
            "F4 acknowledgement missing while menu closed");
        fixture.f4(KMOD_NONE, 1);
        for (const auto modifier : {KMOD_ALT, KMOD_CTRL, KMOD_GUI, KMOD_SHIFT}) fixture.f4(modifier);
        fixture.f4(KMOD_NONE, 0, SDL_KEYUP);
        require(fixture.log().find("issue-marker seq=2 ") == std::string::npos,
            "repeat or modified F4 produced a marker");

        tooie::input::host().set_menu_open(true);
        host::Request keyboard_capture{};
        keyboard_capture.kind = host::RequestKind::Capture;
        keyboard_capture.action = Action::A;
        keyboard_capture.device = Device::Keyboard;
        keyboard_capture.slot = 1;
        require(host::enqueue(keyboard_capture), "F4 keyboard capture queue failed");
        host::tick(false);
        require(fixture.snapshot()->capture.active && !fixture.snapshot()->capture.arming,
            "F4 keyboard capture did not arm");
        fixture.f4();
        host::tick(false);
        require(tooie::input::get_binding(Action::A, Device::Keyboard, 1).code == SDL_SCANCODE_F4 &&
            !fixture.snapshot()->capture.active && fixture.log().find("issue-marker seq=2 ") == std::string::npos,
            "F4 marker stole keyboard capture");
        fixture.f4(KMOD_NONE, 0, SDL_KEYUP);
        // A press during release suppression must also yield to the mapper.
        fixture.f4();
        require(fixture.log().find("issue-marker disabled:") == std::string::npos,
            "F4 marker ran during capture cooldown");
        fixture.f4(KMOD_NONE, 0, SDL_KEYUP);
        fixture.cooldown();
        host::request_close();
        host::note_game_started();
        host::tick(true); // Complete the neutral menu-to-game handoff first.
        fixture.f4();
        require((host::tick(true).physical.buttons & 0x8000) != 0,
            "bound F4 did not reach gameplay A bit");
        require(fixture.snapshot()->notice.find("F4 is bound to A;") != std::string::npos &&
            fixture.log().find("issue-marker seq=2 ") == std::string::npos,
            "bound F4 did not disable the marker with a named notice");
        fixture.f4(KMOD_NONE, 0, SDL_KEYUP);
        host::Request reset{};
        reset.kind = host::RequestKind::ResetBindings;
        require(host::enqueue(reset), "F4 reset bindings queue failed");
        host::tick(true);
        fixture.f4();
        host::tick(true);
        require(fixture.log().find("issue-marker seq=2 ") != std::string::npos &&
            fixture.snapshot()->toast.find("#2") != std::string::npos,
            "reset bindings did not re-enable F4 marker");
        // F: The SDL queue publishes live preferences without changing startup state.
        const auto startup=host::latched_preferences();
        const auto preference=[&](host::Preference key,int value) {
            host::Request request{};
            request.kind=host::RequestKind::Preference;
            request.preference=key;request.value=value;
            require(host::enqueue(request), "preference queue rejected");
            host::tick(true);
        };
        preference(host::Preference::QuietTalonTrot,1);
        preference(host::Preference::Resolution,4);
        require(host::requested_quiet_talon_trot() && host::requested_resolution()==4,
            "live preference not published");
        require(host::latched_preferences().quiet_talon_trot==startup.quiet_talon_trot &&
            host::latched_preferences().resolution==startup.resolution,
            "live preference mutated startup snapshot");
        preference(host::Preference::QuietTalonTrot,2);
        preference(host::Preference::Resolution,9);
        require(host::requested_quiet_talon_trot() && host::requested_resolution()==4,
            "invalid preference changed live request");
        preference(host::Preference::QuietTalonTrot,0);
        preference(host::Preference::Resolution,1);
        require(!host::requested_quiet_talon_trot() && host::requested_resolution()==1,
            "live preference could not return to default");
        preference(host::Preference::QuietTalonTrot,1);
        preference(host::Preference::Resolution,8);
        require(tooie::frontend::settings::flush(), "live preferences did not persist");
        host::shutdown();
        require(!host::requested_quiet_talon_trot() && host::requested_resolution()==1,
            "shutdown retained live request");
        host::initialize(fixture.window,fixture.profile);
        require(host::requested_quiet_talon_trot() && host::requested_resolution()==8,
            "persisted preferences missing on restart");
        std::cout << "baseline input host A-F passed (virtual SDL controller; synthetic focus/keys; "
            "no native focus, keyboard-state or gameplay/hardware acceptance)\n";
        return 0;
    } catch (const std::exception& error) {
        // stderr belongs to the disposable fixture log; stdout remains CTest-visible.
        std::cout << "baseline input host FAIL: " << error.what() << '\n';
        return 1;
    }
}
